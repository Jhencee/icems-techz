    public function changePassword(Request $request): JsonResponse
    {
        // 1. Validate input
        $validated = $request->validate([
            'new_password' => [
                'required',
                'string',
                'min:8',
                'regex:/[a-z]/',
                'regex:/[A-Z]/',
                'regex:/[0-9]/',
                'regex:/[^a-zA-Z0-9]/',
            ],
            'confirm_password' => 'required|string|same:new_password',
        ], [
            'new_password.regex' => 'Password must contain uppercase, lowercase, number, and special character.',
            'confirm_password.same' => 'Passwords do not match.',
        ]);

        // 2. Get authenticated student from Sanctum token
        $bearerToken = $request->bearerToken();
        if (!$bearerToken) {
            return response()->json(['success' => false, 'message' => 'Unauthenticated.'], 401);
        }
        $accessToken = \Laravel\Sanctum\PersonalAccessToken::findToken($bearerToken);
        if (!$accessToken) {
            return response()->json(['success' => false, 'message' => 'Invalid token.'], 401);
        }
        $student = $accessToken->tokenable;

        // 3. Prevent reusing the same password
        if (Hash::check($validated['new_password'], $student->password)) {
            return response()->json([
                'success' => false,
                'message' => 'New password cannot be the same as your current password.',
            ], 422);
        }

        // 4. Update password
        $student->update([
            'password' => Hash::make($validated['new_password']),
            'password_changed' => true,
        ]);

        // 5. Revoke old tokens so they must log in fresh
        $student->tokens()->delete();

        return response()->json([
            'success' => true,
            'message' => 'Password changed successfully.',
        ], 200);
    }

