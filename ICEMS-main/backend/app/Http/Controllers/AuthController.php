    // POST /api/auth/login
    public function login(Request $request)
    {
        $email = $request->input('email');
        $password = $request->input('password');

        // 1. Check admins table
        $admin = \App\Models\Admin::where('email', $email)->first();

        if ($admin && Hash::check($password, $admin->password)) {
            return response()->json([
                'success' => true,
                'user' => [
                    'email' => $admin->email,
                    'name' => $admin->name,
                    'role' => 'admin',
                    'department' => $admin->department,
                    'dashboard' => $this->getAdminDashboard($admin->department),
                ]
            ]);
        }

        // 2. Check registered students
        $student = \App\Models\AllowedStudent::where('email', $email)->first();

        if ($student && Hash::check($password, $student->password)) {
            return response()->json([
                'success' => true,
                'user' => [
                    'email' => $student->email,
                    'first_name' => $student->first_name,
                    'last_name' => $student->last_name,
                    'student_number' => $student->student_number,
                    'role' => 'student',
                ]
            ]);
        }

        // 3. Check allowed_students ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÂ¢Ã¢â€šÂ¬Ã‚Â issue Sanctum token
        $allowed = \App\Models\AllowedStudent::where('email', $email)->first();

        if ($allowed && Hash::check($password, $allowed->password)) {

            $token = $allowed->createToken('student-token')->plainTextToken;

            return response()->json([
                'success' => true,
                'token' => $token,
                'password_changed' => $allowed->password_changed,
                'user' => [
                    'email' => $allowed->email,
                    'first_name' => $allowed->first_name,
                    'last_name' => $allowed->last_name,
                    'student_number' => $allowed->student_number,
                    'course' => $allowed->course,
                    'year' => $allowed->year,
                    'section' => $allowed->section,
                    'role' => 'student',
                ]
            ]);
        }

        // 4. Nothing matched
        return response()->json([
            'success' => false,
            'message' => 'Invalid email or password.'
        ], 401);
    }

