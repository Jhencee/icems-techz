    // POST /api/password/send-code
    public function sendResetCode(Request $request): JsonResponse
    {
        $request->validate(['email' => 'required|email']);

        // Check if email exists in students or allowed_students
        $exists = \App\Models\Student::where('email', $request->email)->exists()
            || \App\Models\AllowedStudent::where('email', $request->email)->exists();
        if (!$exists) {
            return response()->json(['success' => false, 'message' => 'No account found with this email.'], 422);
        }

        PasswordResetCode::where('email', $request->email)->update(['is_used' => true]);

        $code = str_pad(random_int(0, 999999), 6, '0', STR_PAD_LEFT);

        PasswordResetCode::create([
            'email' => $request->email,
            'code' => $code,
            'expires_at' => now()->addMinutes(15),
        ]);

        try {
            Mail::raw(
                "Your password reset code is: {$code}\n\nThis code expires in 15 minutes.",
                fn($m) => $m->to($request->email)->subject('Password Reset Code')
            );
        } catch (\Throwable $e) {
            \Log::error('Mail send failed: ' . $e->getMessage());
        }

        return response()->json([
            'success' => true,
            'message' => 'Verification code sent to your email.',
        ]);
    }

    // POST /api/password/verify-code
    public function verifyCode(Request $request): JsonResponse
    {
        $request->validate([
            'email' => 'required|email',
            'code' => 'required|string|size:6',
        ]);

        $record = PasswordResetCode::where('email', $request->email)
            ->where('code', $request->code)
            ->where('is_used', false)
            ->latest()
            ->first();

        if (!$record || $record->isExpired()) {
            return response()->json([
                'success' => false,
                'message' => 'Invalid or expired code.'
            ], 422);
        }

        $token = Str::random(64);
        $record->update(['token' => $token]);

        return response()->json([
            'success' => true,
            'message' => 'Code verified.',
            'token' => $token,
        ]);
    }

    // POST /api/password/reset
    public function resetPassword(Request $request): JsonResponse
    {
        $request->validate([
            'token' => 'required|string',
            'password' => 'required|min:8|confirmed',
        ]);

        $record = PasswordResetCode::where('token', $request->token)
            ->where('is_used', false)
            ->latest()
            ->first();

        if (!$record || $record->isExpired()) {
            return response()->json([
                'success' => false,
                'message' => 'Invalid or expired token.'
            ], 422);
        }

        Student::where('email', $record->email)->update(['password' => Hash::make($request->password)]);
        \App\Models\AllowedStudent::where('email', $record->email)->update(['password' => Hash::make($request->password)]);

        $record->update(['is_used' => true]);

        return response()->json([
            'success' => true,
            'message' => 'Password reset successfully.',
        ]);
    }

